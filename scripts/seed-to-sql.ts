// scripts/seed-to-sql.ts — gantCalendar
//
// Turns src/data/seed.json (made by `npm run import` from data/schedule.xlsx)
// into one reviewable SQL file that loads the year plan into the shared
// Supabase database:  supabase/seed/calendar-seed.sql
//
//   npm run import       # Excel -> seed.json (validated, unchanged)
//   npm run import:sql   # seed.json -> supabase/seed/calendar-seed.sql
//   then run that SQL file in the tiyum-kitot SQL editor (or with psql).
//
// No keys, no network. The SQL runs in one transaction, upserts by id,
// removes Excel rows that the new workbook dropped, and aborts on any
// count mismatch. It never touches the `events` table (user events).

import { createHash, randomUUID } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

interface Category {
  id: string;
  name: string;
  rawLabel?: string;
  group?: 'schools' | 'center';
  groups?: number;
  weeklyHoursPerGroup?: number;
  color: string;
  kind: 'course' | 'holiday' | 'special' | 'milestone' | 'custom';
}
interface MonthMeta {
  key: string;
  title: string;
  hebrewRange: string;
  milestones: string[];
  hebrewDates: Record<string, string>;
}
interface SeedEvent {
  id: string;
  title: string;
  date: string;
  endDate?: string;
  allDay: boolean;
  startTime?: string;
  endTime?: string;
  categoryId: string;
  location?: string;
  notes?: string;
  color?: string;
  source: string;
}
interface SeedData {
  categories: Category[];
  months: MonthMeta[];
  events: SeedEvent[];
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const seedPath = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'src', 'data', 'seed.json');
const outPath = process.argv[3] ? path.resolve(process.argv[3]) : path.join(root, 'supabase', 'seed', 'calendar-seed.sql');
const xlsxPath = path.join(root, 'data', 'schedule.xlsx');

const raw = await readFile(seedPath);
const seed = JSON.parse(raw.toString('utf8')) as SeedData;
const seedSha = createHash('sha256').update(raw).digest('hex');
const xlsxSha = existsSync(xlsxPath) ? createHash('sha256').update(await readFile(xlsxPath)).digest('hex') : null;

// ---- structural checks (content was already validated by `npm run import`)
const problems: string[] = [];
const categoryIds = new Set<string>();
for (const c of seed.categories) {
  if (categoryIds.has(c.id)) problems.push(`duplicate category id ${c.id}`);
  categoryIds.add(c.id);
  if (!/^#[0-9A-Fa-f]{6}$/.test(c.color)) problems.push(`category ${c.id}: bad color ${c.color}`);
}
const monthKeys = new Set<string>();
for (const m of seed.months) {
  if (!/^\d{4}-\d{2}$/.test(m.key)) problems.push(`month key ${m.key}`);
  if (monthKeys.has(m.key)) problems.push(`duplicate month ${m.key}`);
  monthKeys.add(m.key);
}
const eventIds = new Set<string>();
for (const e of seed.events) {
  if (!e.id.startsWith('xlsx:')) problems.push(`entry ${e.id}: id must start with xlsx:`);
  if (eventIds.has(e.id)) problems.push(`duplicate entry id ${e.id}`);
  eventIds.add(e.id);
  if (!categoryIds.has(e.categoryId)) problems.push(`entry ${e.id}: unknown category ${e.categoryId}`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date)) problems.push(`entry ${e.id}: bad date ${e.date}`);
}
if (problems.length > 0) {
  console.error(`seed.json failed ${problems.length} check(s):\n- ${problems.slice(0, 20).join('\n- ')}`);
  process.exit(1);
}

// ---- SQL helpers
const q = (v: string | null | undefined): string => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: number | null | undefined): string => (v == null ? 'null' : String(Number(v)));
const b = (v: boolean): string => (v ? 'true' : 'false');
const arr = (xs: string[]): string => (xs.length === 0 ? `'{}'::text[]` : `array[${xs.map(q).join(', ')}]::text[]`);

const batch = randomUUID();
const now = new Date().toISOString();
const counts = { categories: seed.categories.length, months: seed.months.length, entries: seed.events.length };

const categoryRows = seed.categories.map(
  (c, i) =>
    `  (${q(c.id)}, ${q(c.name)}, ${q(c.rawLabel)}, ${q(c.group)}, ${n(c.groups)}, ${n(c.weeklyHoursPerGroup)}, ${q(c.color)}, ${q(c.kind)}, ${i}, '${batch}')`,
);
const monthRows = seed.months.map(
  (m, i) =>
    `  (${q(m.key)}, ${q(m.title)}, ${q(m.hebrewRange)}, ${arr(m.milestones)}, ${q(JSON.stringify(m.hebrewDates))}::jsonb, ${i}, '${batch}')`,
);
const entryRows = seed.events.map(
  (e) =>
    `  (${q(e.id)}, ${q(e.title)}, ${q(e.date)}, ${q(e.endDate)}, ${b(e.allDay)}, ${q(e.startTime)}, ${q(e.endTime)}, ${q(e.categoryId)}, ${q(e.location)}, ${q(e.notes)}, ${q(e.color)}, '${batch}')`,
);

const sql = `-- calendar-seed.sql — GENERATED by scripts/seed-to-sql.ts on ${now}. Do not edit by hand.
-- Source: src/data/seed.json  sha256=${seedSha}
-- Workbook: data/schedule.xlsx  sha256=${xlsxSha ?? 'not found'}
-- Expected: ${counts.categories} categories, ${counts.months} months, ${counts.entries} schedule entries.
-- Run in the tiyum-kitot SQL editor. Safe to run again. Never touches public.events.

begin;

do $$
begin
  if to_regclass('public.calendar_schedule') is null then
    raise exception 'Run 20261022090000_calendar_into_shared_db.sql first (calendar tables are missing).';
  end if;
end $$;

insert into public.calendar_import_batches
  (id, source_file, source_sha256, categories_count, months_count, entries_count, note)
values
  ('${batch}', 'data/schedule.xlsx -> src/data/seed.json', '${seedSha}', ${counts.categories}, ${counts.months}, ${counts.entries}, ${q(xlsxSha ? `xlsx sha256 ${xlsxSha}` : '')})
on conflict (id) do update set imported_at = now();

insert into public.calendar_categories
  (id, name, raw_label, category_group, groups, weekly_hours_per_group, color, kind, sort_order, batch_id)
values
${categoryRows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, raw_label = excluded.raw_label, category_group = excluded.category_group,
  groups = excluded.groups, weekly_hours_per_group = excluded.weekly_hours_per_group,
  color = excluded.color, kind = excluded.kind, sort_order = excluded.sort_order, batch_id = excluded.batch_id;

insert into public.calendar_months
  (key, title, hebrew_range, milestones, hebrew_dates, sort_order, batch_id)
values
${monthRows.join(',\n')}
on conflict (key) do update set
  title = excluded.title, hebrew_range = excluded.hebrew_range, milestones = excluded.milestones,
  hebrew_dates = excluded.hebrew_dates, sort_order = excluded.sort_order, batch_id = excluded.batch_id;

insert into public.calendar_schedule
  (id, title, date, end_date, all_day, start_time, end_time, category_id, location, notes, color, batch_id)
values
${entryRows.join(',\n')}
on conflict (id) do update set
  title = excluded.title, date = excluded.date, end_date = excluded.end_date, all_day = excluded.all_day,
  start_time = excluded.start_time, end_time = excluded.end_time, category_id = excluded.category_id,
  location = excluded.location, notes = excluded.notes, color = excluded.color, batch_id = excluded.batch_id;

-- Rows the new workbook no longer contains. Categories are never deleted
-- here, because user events may point at them.
delete from public.calendar_schedule where batch_id is distinct from '${batch}';
delete from public.calendar_months   where batch_id is distinct from '${batch}';

do $$
declare
  n_cat int; n_mon int; n_sch int;
begin
  select count(*) into n_cat from public.calendar_categories where batch_id = '${batch}';
  select count(*) into n_mon from public.calendar_months     where batch_id = '${batch}';
  select count(*) into n_sch from public.calendar_schedule   where batch_id = '${batch}';
  if n_cat <> ${counts.categories} or n_mon <> ${counts.months} or n_sch <> ${counts.entries}
     or (select count(*) from public.calendar_schedule) <> ${counts.entries} then
    raise exception 'calendar seed mismatch: categories %/${counts.categories}, months %/${counts.months}, entries %/${counts.entries}. Nothing was saved.',
      n_cat, n_mon, n_sch;
  end if;
  raise notice 'calendar seed OK: % categories, % months, % entries (batch ${batch})', n_cat, n_mon, n_sch;
end $$;

commit;
`;

await mkdir(path.dirname(outPath), { recursive: true });
await writeFile(outPath, sql, 'utf8');
console.log(
  `wrote ${path.relative(process.cwd(), outPath)} — ${counts.categories} categories, ${counts.months} months, ${counts.entries} entries (batch ${batch})`,
);
